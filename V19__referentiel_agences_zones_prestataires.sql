set zone_distribution_id = z.id,
    prestataire          = t.prestataire,
    cout_deplacement     = t.pu,
    updated_at           = now()
from tmp_ref_agence t
join zone_distribution z on z.code = t.zone
where o.type = 'AGENCE' and o.code = t.code_agence;
